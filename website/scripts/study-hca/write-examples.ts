/** Regenerates docs/study-hca/examples from the fictional cases. Run from website/. */
import { writeFileSync } from "node:fs";
import { FICTIONAL_CASES, FICTIONAL_REFUSED_CASES } from "../../src/lib/studyTimed/fictionalCases";
import { BATCH_SCHEMA, BATCH_SCHEMA_VERSION, resultsToCsv, runBatch } from "../../src/lib/studyTimed/batch";

const dir = "docs/study-hca/examples";
const cases = [...FICTIONAL_CASES.map((c) => c.input), ...FICTIONAL_REFUSED_CASES];
writeFileSync(`${dir}/fictional-cases.json`, JSON.stringify({ schema: BATCH_SCHEMA, schema_version: BATCH_SCHEMA_VERSION, cases }, null, 2) + "\n");
const caseCols = ["study_case_id", "time_basis", "age_years", "weight_kg", "serum_creatinine_mg_dl", "scr_collected_at", "renal_replacement_therapy", "history_complete_attested", "draw_time"] as const;
writeFileSync(`${dir}/fictional-cases.csv`, [caseCols.join(","), ...cases.map((c) => caseCols.map((k) => String(c[k])).join(","))].join("\n") + "\n");
const doseLines = ["study_case_id,start,dose_mg,infusion_minutes,end"];
for (const c of cases) for (const d of c.doses) doseLines.push([c.study_case_id, d.start, d.dose_mg, d.infusion_minutes ?? "", d.end ?? ""].join(","));
writeFileSync(`${dir}/fictional-doses.csv`, doseLines.join("\n") + "\n");
writeFileSync(`${dir}/expected-predictions.csv`, resultsToCsv(runBatch(cases)));
console.log("examples written");

// Reviewer case set (generated so the numbers cannot be mistyped).
const results = runBatch(cases);
const md: string[] = [
  "# Fictional reviewer case set",
  "",
  "Generated by `scripts/study-hca/write-examples.ts` from the fictional cases. Invented data; no real patient. An independent reviewer can reproduce every predicted value without Vancomyzer code:",
  "",
  "1. Population parameters (Colin 2019, article Eq. 6 with Table 3 values, as shipped): PMA = age + 40/52 years; CL = 5.31 × (WT/70)^0.75 × FMat × FDecline × FSCR with FMat = PMAwk^2.89/(PMAwk^2.89 + 46.4^2.89), PMAwk = 52 × PMA, FDecline = 1/(1 + (PMA/61.6)^2.24), FSCR = exp(−0.649 × (SCr − SCRstd)), SCRstd = exp(−1.228 + 0.672 × log10(PMA) + 6.27 × exp(−3.11 × PMA)); V1 = 42.9 × WT/70; V2 = 41.7 × WT/70; Q = 3.22 × (WT/70)^0.75. (Weight floor 30 kg and age floor 18 y do not bind in these cases.)",
  "2. Two-compartment model with zero-order infusions at the listed actual times, central concentration A1/V1 at the draw. Ignore doses that start after the draw; truncate an infusion running at the draw at the draw time.",
  "3. Any accurate method (closed-form superposition or an ODE solver) should agree to about 1e-6 relative. The project's own ODE reference agrees to better than 1e-8.",
  "",
  "This set supports reproduction of the software only. It is not clinical validation and no independent sign-off is claimed.",
  "",
  "| Case | Doses (start, mg, infusion) | Draw | Age / kg / SCr | Status | Predicted mg/L (unrounded) | CL / V1 / Q / V2 | Notes |",
  "|---|---|---|---|---|---|---|---|",
];
cases.forEach((c, i) => {
  const r = results[i];
  const doses = c.doses.map((d) => `${d.start}, ${d.dose_mg}, ${d.infusion_minutes !== undefined ? `${d.infusion_minutes} min` : `to ${d.end}`}`).join("; ");
  const p = r.model_parameters;
  const notes = [...r.warnings, ...r.reasons].map((x) => x.code).join(", ");
  md.push(`| ${c.study_case_id} | ${doses} | ${c.draw_time} | ${c.age_years} / ${c.weight_kg} / ${c.serum_creatinine_mg_dl} | ${r.status} | ${r.predicted_concentration_mg_l ?? "—"} | ${p ? [p.CL_L_h, p.V1_L, p.Q_L_h, p.V2_L].map((v) => v.toPrecision(10)).join(" / ") : "—"} | ${notes} |`);
});
md.push("", "Times are elapsed hours except FICT-A05, which uses clock times with explicit offsets (draw 24.5 h after the first dose start).", "");
writeFileSync("docs/study-hca/REVIEWER_CASES.md", md.join("\n"));
